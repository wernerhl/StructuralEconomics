"""Merge bib/part*.bib into references.bib.

- Entries with the same key are merged: the entry with more fields wins,
  and any field missing from it is filled from the others. Conflicting
  titles/years for the same key are reported.
- Likely duplicates under different keys (same normalized title and year)
  are reported, not merged.
- Every key cited in chapters/*.tex must exist in the merged file; missing
  keys are reported.

Usage: python3 tools/merge_bib.py   (from the repository root)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def parse(text):
    entries, i = [], 0
    while True:
        m = re.compile(r'@(\w+)\s*\{\s*([^,\s]+)\s*,').search(text, i)
        if not m:
            return entries
        depth, j = 1, m.end()
        start_body = j
        while depth and j < len(text):
            depth += {'{': 1, '}': -1}.get(text[j], 0)
            j += 1
        if depth:
            sys.exit(f"unbalanced braces in entry {m.group(2)}")
        body = text[start_body:j - 1]
        fields, k = {}, 0
        for fm in re.finditer(r'(\w[\w-]*)\s*=\s*', body):
            if fm.start() < k:
                continue
            name, p = fm.group(1).lower(), fm.end()
            if p < len(body) and body[p] == '{':
                d, q = 1, p + 1
                while d and q < len(body):
                    d += {'{': 1, '}': -1}.get(body[q], 0)
                    q += 1
                val = body[p + 1:q - 1]
            elif p < len(body) and body[p] == '"':
                q = body.index('"', p + 1) + 1
                val = body[p + 1:q - 1]
            else:
                q = p
                while q < len(body) and body[q] not in ',\n':
                    q += 1
                val = body[p:q].strip()
            fields[name] = val.strip()
            k = q
        entries.append((m.group(1).lower(), m.group(2), fields))
        i = j


def norm(s):
    s = re.sub(r'\\[a-zA-Z]+|[{}\\\'"`^~]', '', s.lower())
    return re.sub(r'[^a-z0-9]+', ' ', s).strip()


def main():
    merged, origin, problems = {}, {}, []
    for part in sorted((ROOT / 'bib').glob('part*.bib')):
        for typ, key, fields in parse(part.read_text()):
            if key in merged:
                t0, f0 = merged[key]
                for fld in ('title', 'year'):
                    if fld in f0 and fld in fields and norm(f0[fld]) != norm(fields[fld]):
                        problems.append(f"key {key}: {fld} differs between {origin[key]} and {part.name}: "
                                        f"'{f0[fld]}' vs '{fields[fld]}'")
                base, other = (fields, f0) if len(fields) > len(f0) else (f0, fields)
                merged[key] = (typ if base is fields else t0, {**other, **base})
                origin[key] += '+' + part.name
            else:
                merged[key] = (typ, fields)
                origin[key] = part.name
    seen = {}
    for key, (typ, f) in merged.items():
        sig = (norm(f.get('title', ''))[:60], f.get('year', ''))
        if sig[0] and sig in seen:
            problems.append(f"possible duplicate: {seen[sig]} and {key} ({f.get('title')}, {f.get('year')})")
        seen.setdefault(sig, key)
        for req in ('author', 'title', 'year') if typ != 'misc' else ('title',):
            if req not in f and not (req == 'author' and 'editor' in f):
                problems.append(f"{key}: missing {req}")
    order = ['author', 'editor', 'title', 'journal', 'booktitle', 'publisher', 'address', 'institution',
             'series', 'type', 'number', 'volume', 'edition', 'year', 'month', 'pages', 'doi', 'url', 'note',
             'x-verify']
    out = ["% Structural Economics: The General Case -- bibliography",
           "% Generated by tools/merge_bib.py from bib/part*.bib. Edit the parts, then re-run.",
           "% Key convention: docs/bibliography.md", ""]
    for key in sorted(merged):
        typ, f = merged[key]
        names = sorted(f, key=lambda n: (order.index(n) if n in order else len(order), n))
        out.append(f"@{typ}{{{key},")
        out += [f"  {n} = {{{f[n]}}}," for n in names]
        out.append("}\n")
    (ROOT / 'references.bib').write_text("\n".join(out))
    cited = set()
    for tex in (ROOT / 'chapters').glob('*.tex'):
        for m in re.finditer(r'\\(?:no)?cite[a-zA-Z]*\*?(?:\[[^\]]*\]){0,2}\{([^}]+)\}', tex.read_text()):
            cited |= {k.strip() for k in m.group(1).split(',') if k.strip() and k.strip() != '*'}
    missing = sorted(cited - set(merged))
    unused = sorted(set(merged) - cited)
    nverify = sum('x-verify' in f for _, f in merged.values())
    print(f"{len(merged)} entries ({nverify} with x-verify), {len(cited)} cited keys, "
          f"{len(missing)} missing, {len(unused)} unused")
    for k in missing:
        problems.append(f"cited but not defined: {k}")
    for p in problems:
        print("  -", p)
    return 1 if missing else 0


if __name__ == '__main__':
    sys.exit(main())
